"""Save / load the per-model results that the scripts in analysis/ consume.

Each model notebook ends with ``save_run(...)``, which writes into
``results/<model_key>/``:

    history.json      per-epoch train/val loss and accuracy
    metrics.json      test accuracy, weighted precision/recall/F1, macro ROC-AUC,
                      parameter count and the 4x4 confusion matrix
    test_outputs.npz  softmax probabilities + true labels on the test set
                      (needed only for the ROC / precision-recall curves)

The analysis scripts read only these files, so the comparison figures can be
regenerated by anyone without re-training.
"""
import json

import numpy as np

from .config import CLASSES, RESULTS_DIR

MODEL_KEYS = ["mlp", "resnet18", "cnn_lstm", "vit"]
DISPLAY = {"mlp": "MLP", "resnet18": "ResNet18", "cnn_lstm": "CNN-LSTM", "vit": "ViT"}
COLORS = {"MLP": "tab:blue", "ResNet18": "tab:orange", "CNN-LSTM": "tab:green", "ViT": "tab:red"}


def roc_auc_macro(y_true, probs):
    from sklearn.metrics import roc_auc_score
    from sklearn.preprocessing import label_binarize

    y_true_bin = label_binarize(y_true, classes=list(range(len(CLASSES))))
    return roc_auc_score(y_true_bin, probs, average="macro", multi_class="ovr")


def save_run(key, model, history, test_loader):
    """Evaluate ``model`` on the test set and write history / metrics / outputs for ``key``."""
    from .engine import evaluate_model, get_probs_and_labels

    out_dir = RESULTS_DIR / key
    out_dir.mkdir(parents=True, exist_ok=True)

    _, acc, prec, rec, f1, cm = evaluate_model(model, test_loader)
    probs, labels = get_probs_and_labels(model, test_loader)

    metrics = {
        "model": DISPLAY[key],
        "accuracy": float(acc),
        "precision": float(prec),
        "recall": float(rec),
        "f1": float(f1),
        "roc_auc_macro": float(roc_auc_macro(labels, probs)),
        "n_params": int(sum(p.numel() for p in model.parameters())),
        "confusion_matrix": np.asarray(cm).tolist(),
    }
    (out_dir / "history.json").write_text(json.dumps(history, indent=2))
    (out_dir / "metrics.json").write_text(json.dumps(metrics, indent=2))
    np.savez_compressed(out_dir / "test_outputs.npz", probs=probs, labels=labels)
    print(f"Saved results for {DISPLAY[key]} -> {out_dir}")
    return metrics


def load_runs(need_outputs=False):
    """Return {display_name: {"history", "metrics", "probs", "labels"}} for every model that has results.

    With ``need_outputs=True`` only models that also have ``test_outputs.npz`` are returned.
    """
    runs = {}
    for key in MODEL_KEYS:
        d = RESULTS_DIR / key
        hist_f, met_f, out_f = d / "history.json", d / "metrics.json", d / "test_outputs.npz"
        if not (hist_f.exists() and met_f.exists()):
            continue
        run = {
            "history": json.loads(hist_f.read_text()),
            "metrics": json.loads(met_f.read_text()),
            "probs": None,
            "labels": None,
        }
        if out_f.exists():
            z = np.load(out_f)
            run["probs"], run["labels"] = z["probs"], z["labels"]
        elif need_outputs:
            print(f"[skip] {DISPLAY[key]}: no test_outputs.npz yet (re-run its notebook)")
            continue
        runs[DISPLAY[key]] = run
    if not runs:
        raise SystemExit(f"No results found in {RESULTS_DIR}. Run the model notebooks first.")
    return runs
